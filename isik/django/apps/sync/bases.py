"""
The sync log's abstract base - `AbstractSyncLogEntry` - for a project to own the log's table: subclass it, and
name the subclass in `ISIK['DJANGO']['SYNC']['LOG_MODEL']`.

    class SyncLogEntry(AbstractSyncLogEntry):
        class Meta:
            db_table = "sync_log"

    ISIK = {"DJANGO": {"SYNC": {"LOG_MODEL": "sync.SyncLogEntry"}}}

Each concrete subclass gets the log's rules when it's prepared, whatever its own Meta inherits: append-only,
no TRUNCATE, and the index the feed reads it by. Their names are stable - a project may name them. Pruning
goes through the protections with `pgtrigger.ignore` - see `log.prune_sync_log()`.
"""

import pgtrigger
from django.db import models
from django.db.models.functions import Now
from django.db.models.signals import class_prepared

from isik._internal.translation import gettext_lazy
from isik.django.apps.common.db.constraints import fitted_name
from isik.django.apps.common.db.models import DatabaseUUID7, new_primary_key
from isik.django.apps.common.db.triggers import ProtectTruncate
from isik.django.apps.sync.choices import Operation


class SequenceField(models.BigIntegerField):
    """
    A bigint the database numbers - `GENERATED BY DEFAULT AS IDENTITY` - on a column that isn't the primary key.
    Rows taking it are written in SQL, by triggers, which never name it.
    """

    def db_type_suffix(self, connection):
        return "GENERATED BY DEFAULT AS IDENTITY"


class AbstractSyncLogEntry(models.Model):
    """
    One change a client syncing may need to hear of: a row of a synced model written or deleted, or a person
    granted or revoked a scope - written by a trigger in the transaction that made the change. Its position is
    (`xid`, `seq`): the feed serves an entry only once every transaction that could still write one before it
    has ended, so a cursor never passes a change that commits late. It holds no row data: the feed reads the
    row as REST shows it when it serves the change.
    """

    # new_primary_key()'s for an entry written in Python - the pruning mark; the triggers write theirs in SQL.
    id = models.UUIDField(
        primary_key=True,
        editable=False,
        default=new_primary_key,
        db_default=DatabaseUUID7(),
        help_text=gettext_lazy("The entry's own identifier."),
        db_comment="The entry's own identifier - a uuid7 the database makes, for an entry a trigger writes.",
        verbose_name=gettext_lazy("ID"),
    )
    xid = models.BigIntegerField(
        help_text=gettext_lazy("The transaction that made the change."),
        db_comment="pg_current_xact_id() of the transaction that made the change - the first half of the "
        "entry's position.",
        verbose_name=gettext_lazy("transaction"),
    )
    seq = SequenceField(
        help_text=gettext_lazy("The entry's place among the transaction's own."),
        db_comment="A number the database gives each entry, rising - the second half of the entry's position.",
        verbose_name=gettext_lazy("sequence"),
    )
    op = models.CharField(
        max_length=16,
        choices=Operation.choices,
        help_text=gettext_lazy("What happened."),
        db_comment="upsert or delete of a row, scope_granted or scope_revoked for a person, or pruned - where "
        "pruning cut the log.",
        verbose_name=gettext_lazy("operation"),
    )
    model = models.CharField(
        max_length=100,
        null=True,
        blank=True,
        help_text=gettext_lazy("The synced model the row is of, as the feed names it."),
        db_comment="The name syncs() gave the row's model. Null for a scope's or pruning's entry.",
        verbose_name=gettext_lazy("model"),
    )
    object_id = models.CharField(
        max_length=255,
        null=True,
        blank=True,
        help_text=gettext_lazy("The primary key of the row."),
        db_comment="The row's primary key, as text. Not a key: the row may be deleted, and the entry stays.",
        verbose_name=gettext_lazy("object id"),
    )
    scope = models.TextField(
        null=True,
        blank=True,
        help_text=gettext_lazy("The scope the row is in after the change, or the scope granted or revoked."),
        db_comment="<kind>:<id> - the row's scope after the change, or the scope granted or revoked. Null for a "
        "row in no scope.",
        verbose_name=gettext_lazy("scope"),
    )
    old_scope = models.TextField(
        null=True,
        blank=True,
        help_text=gettext_lazy("The scope the row was in before it moved, when it moved."),
        db_comment="<kind>:<id> - the row's scope before an update moving it to another. Null unless it moved.",
        verbose_name=gettext_lazy("old scope"),
    )
    member = models.CharField(
        max_length=255,
        null=True,
        blank=True,
        help_text=gettext_lazy("The person granted or revoked the scope."),
        db_comment="The primary key of the user granted or revoked the scope, as text. Null for a row's entry.",
        verbose_name=gettext_lazy("member"),
    )
    created_at = models.DateTimeField(
        db_default=Now(),
        help_text=gettext_lazy("When the change was made."),
        db_comment="When the transaction making the change began - what retention prunes by.",
        verbose_name=gettext_lazy("created at"),
    )

    class Meta:
        abstract = True

    def __str__(self):
        return f"{self.op} {self.model or self.scope} {self.object_id or self.member or ''}".rstrip()


def _hold_to_the_rules(sender, **kwargs):
    # On every concrete subclass, as the notifications ledger's: Meta.triggers and indexes on an abstract base
    # would reach only a subclass whose Meta inherits the base's.
    if sender._meta.abstract or sender._meta.proxy or not issubclass(sender, AbstractSyncLogEntry):
        return
    table = sender._meta.db_table
    pgtrigger.register(
        pgtrigger.Protect(name="protect_sync_log_change", operation=pgtrigger.Update | pgtrigger.Delete),
        ProtectTruncate(name="protect_sync_log_truncate"),
    )(sender)
    position = models.Index(
        fields=["xid", "seq"], name=fitted_name(table, "position", limit=models.Index.max_name_length)
    )
    # A new list, recorded where a migration's state is read from - see the notifications ledger's rules.
    sender._meta.indexes = [*sender._meta.indexes, position]
    sender._meta.original_attrs["indexes"] = sender._meta.indexes


class_prepared.connect(_hold_to_the_rules, dispatch_uid="isik_sync_log_rules")
