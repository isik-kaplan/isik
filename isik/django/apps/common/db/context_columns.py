"""
Real, typed columns on pghistory's own context table - one row per request, task or `pghistory.context()` - from
the keys its metadata holds: `AddContextColumn`, a migration operation, and `context_rows()`, reading them.

pghistory's `Context` model is its own and can't be given a field, and pghistory writes its rows itself. A column
Postgres generates from the row's metadata needs neither: it's filled on every write of the row, whoever writes it.

    # yourapp/migrations/0007_context_columns.py
    class Migration(migrations.Migration):
        dependencies = [("yourapp", "0006_..."), ("pghistory", "0006_delete_aggregateevent")]
        operations = [AddContextColumn("request_id", "uuid"), AddContextColumn("correlation_id", "uuid")]

    WidgetEvent.objects.filter(pgh_context__in=context_rows(correlation_id=correlation))
"""

import re

from django.db import connection
from django.db.migrations.operations.base import Operation
from django.db.models.expressions import RawSQL

from isik._internal.translation import gettext as _
from isik.django.apps.common.db.constraints import fitted_name


# What a column may be called, and a key it reads - a plain identifier, so neither needs quoting into SQL.
_IDENTIFIER = re.compile(r"^[a-z_][a-z0-9_]*$")
# The context table's own columns, which a generated one can't take the name of.
_OWN_COLUMNS = ("id", "created_at", "updated_at", "metadata")
# A UUID as Postgres reads one - hyphenated or 32 hex digits, in either case - and nothing around it.
_UUID = r"^[0-9a-fA-F]{8}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{12}$"
UUID_PATTERN = re.compile(_UUID.removeprefix("^").removesuffix("$"))


def _context_table():
    from pghistory.models import Context

    return Context._meta.db_table


def _generated(key, column_type):
    """The expression a column of `column_type` is generated by, from the metadata's `key`."""
    value = f"(metadata ->> '{key}')"
    if column_type == "text":
        return value
    # A value that isn't a UUID is held as NULL: a cast failing would refuse the context row, and with it the write.
    return f"(CASE WHEN {value} ~ '{_UUID}' THEN {value}::uuid END)"


class AddContextColumn(Operation):
    """
    Adds `name` to pghistory's context table: a column of `column_type` - `"uuid"` or `"text"` - that Postgres
    generates from the metadata's `key` (`name`, unless given), and an index on it unless `index=False`. A value
    a `"uuid"` column can't read is held as NULL; the metadata keeps it as written. Reversed, the column and its
    index go.

    Put it in a migration of your own that depends on pghistory's. Adding it rewrites the context table once.
    """

    reversible = True
    reduces_to_sql = True
    COLUMN_TYPES = ("uuid", "text")

    def __init__(self, name, column_type, key=None, index=True):
        key = key or name
        if not _IDENTIFIER.match(name) or not _IDENTIFIER.match(key):
            raise ValueError(
                _("A context column's name and key are lowercase identifiers - not %(name)r and %(key)r.")
                % {"name": name, "key": key}
            )
        if name in _OWN_COLUMNS:
            raise ValueError(_("%(name)s is a column of pghistory's context table already.") % {"name": name})
        if column_type not in self.COLUMN_TYPES:
            raise ValueError(
                _("A context column is %(types)s, not %(type)r.")
                % {"types": " or ".join(self.COLUMN_TYPES), "type": column_type}
            )
        self.name, self.column_type, self.key, self.index = name, column_type, key, index

    def deconstruct(self):
        kwargs = {"name": self.name, "column_type": self.column_type}
        if self.key != self.name:
            kwargs["key"] = self.key
        if not self.index:
            kwargs["index"] = False
        return self.__class__.__qualname__, [], kwargs

    def state_forwards(self, app_label, state):
        # pghistory's model is as pghistory declares it - the column is the database's alone.
        pass

    def _names(self, schema_editor):
        table = _context_table()
        quote = schema_editor.quote_name
        return quote(table), quote(self.name), quote(fitted_name(table, self.name))

    def database_forwards(self, app_label, schema_editor, from_state, to_state):
        table, column, index = self._names(schema_editor)
        schema_editor.execute(
            f"ALTER TABLE {table} ADD COLUMN {column} {self.column_type} "
            f"GENERATED ALWAYS AS {_generated(self.key, self.column_type)} STORED"
        )
        if self.index:
            schema_editor.execute(f"CREATE INDEX {index} ON {table} ({column})")

    def database_backwards(self, app_label, schema_editor, from_state, to_state):
        table, column, _index = self._names(schema_editor)
        # Its index goes with it.
        schema_editor.execute(f"ALTER TABLE {table} DROP COLUMN {column}")

    def describe(self):
        return f"Add {self.column_type} column {self.name} to pghistory's context table, from its {self.key} key"

    @property
    def migration_name_fragment(self):
        return f"context_{self.name}"


def context_rows(**lookup):
    """
    pghistory's context rows whose column `AddContextColumn` added equals a value - `context_rows(request_id=...)`
    - as a queryset of its `Context`, for filtering events by: `pgh_context__in=context_rows(...)`.
    """
    from pghistory.models import Context

    if len(lookup) != 1:
        raise TypeError(_("context_rows() takes one column and its value."))
    [(name, value)] = lookup.items()
    if not _IDENTIFIER.match(name) or name in _OWN_COLUMNS:
        raise ValueError(_("%(name)r isn't a column AddContextColumn adds.") % {"name": name})
    table, column = connection.ops.quote_name(_context_table()), connection.ops.quote_name(name)
    return Context.objects.filter(pk__in=RawSQL(f"SELECT id FROM {table} WHERE {column} = %s", [value]))


__all__ = ["AddContextColumn", "context_rows"]
